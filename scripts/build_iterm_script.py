#!/usr/bin/env python3
"""Build one standard iTerm2 Basic script, without installing or running it."""
import base64
import io
from pathlib import Path
import zipfile

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "dist" / "tmux_toolbelt.py"


def build():
    buffer = io.BytesIO()
    with zipfile.ZipFile(buffer, "w", zipfile.ZIP_DEFLATED) as archive:
        for path in sorted([*(ROOT / "toolbelt").rglob("*"), *(ROOT / name for name in ("LICENSE", "NOTICE", "THIRD_PARTY.md"))]):
            if path.is_file() and "__pycache__" not in path.parts and path.suffix != ".pyc":
                info = zipfile.ZipInfo(path.relative_to(ROOT).as_posix(), (2020, 1, 1, 0, 0, 0))
                info.external_attr = 0o644 << 16
                archive.writestr(info, path.read_bytes(), compress_type=zipfile.ZIP_DEFLATED)
    encoded = base64.b64encode(buffer.getvalue()).decode("ascii")
    entry = (ROOT / "tmux_toolbelt.py").read_text()
    loader = '''#!/usr/bin/env python3
# Generated by scripts/build_iterm_script.py; source is in toolbelt/.
# Unpacks only this project's files to a private temporary directory.
import base64 as _base64
import sys as _sys
import tempfile as _tempfile
import zipfile as _zipfile
import io as _io
_payload = %r
_bundle = _tempfile.TemporaryDirectory(prefix="iterm2-tmux-toolbelt-")
with _zipfile.ZipFile(_io.BytesIO(_base64.b64decode(_payload))) as _archive:
    _archive.extractall(_bundle.name)
_sys.path.insert(0, _bundle.name)
''' % encoded
    OUTPUT.parent.mkdir(exist_ok=True)
    OUTPUT.write_text(loader + entry.replace("#!/usr/bin/env python3\n", "", 1))
    print("Generated dist/tmux_toolbelt.py (Basic script; not installed)")


if __name__ == "__main__":
    build()
