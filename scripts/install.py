#!/usr/bin/env python3
"""Explicit opt-in installer. Does not toggle API or run a script."""
import argparse
from pathlib import Path
import shutil
import sys
from build_iterm_script import build, OUTPUT


def main():
    parser = argparse.ArgumentParser(description="安装/卸载 tmux Toolbelt，需显式 --confirm。")
    parser.add_argument("--confirm", action="store_true", help="确认复制/删除脚本文件")
    parser.add_argument("--autolaunch", action="store_true", help="安装到 AutoLaunch，iTerm2 下次启动时自动运行")
    parser.add_argument("--uninstall", action="store_true")
    parser.add_argument("--update", action="store_true", help="仅更新已安装的本项目标记脚本")
    args = parser.parse_args()
    root = Path.home() / "Library" / "Application Support" / "iTerm2" / "Scripts"
    target = (root / "AutoLaunch" if args.autolaunch else root) / "tmux_toolbelt.py"
    if not args.confirm:
        print("预览：" + ("删除 " if args.uninstall else "更新 " if args.update else "安装 ") + str(target))
        print("不会开启 Python API 或运行脚本。确认后添加 --confirm。")
        return
    if args.uninstall:
        if target.is_symlink():
            sys.exit("拒绝删除符号链接，请自行检查。")
        if not target.exists():
            print("指定脚本未安装。")
            return
        if not target.is_file() or not target.read_text().startswith("#!/usr/bin/env python3\n# Generated by scripts/build_iterm_script.py;"):
            sys.exit("拒绝删除不属于本项目的文件。")
        target.unlink()
        print("已删除脚本；请在 Scripts > Manage > Console 停止其运行实例。")
        return
    build()
    other = (root if args.autolaunch else root / "AutoLaunch") / "tmux_toolbelt.py"
    if args.update:
        if target.is_symlink() or not target.is_file() or not target.read_text().startswith("#!/usr/bin/env python3\n# Generated by scripts/build_iterm_script.py;"):
            sys.exit("拒绝更新未知脚本或符号链接。")
        shutil.copyfile(OUTPUT, target)
        print("已更新本项目脚本；请仅在 Scripts Console 停止旧插件后重新运行，勿退出 iTerm2。")
        return
    if target.exists() or target.is_symlink() or other.exists() or other.is_symlink():
        sys.exit("已存在同名脚本，未覆盖。请检查/卸载旧版本后再安装。")
    if root.is_symlink() or target.parent.is_symlink():
        sys.exit("Scripts 目录是符号链接，请先自行确认目标位置。")
    target.parent.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(OUTPUT, target)
    print("已安装 " + str(target))
    print("尚未运行脚本，也未修改 Python API 设置。")


if __name__ == "__main__":
    main()
